#!/usr/bin/env node
// Writes src-overrides/amino-schema.ts from the chain's amino schema, read on
// stdin. Run from packages/sparkdreamjs after every proto sync:
//
//   (cd <chain> && go run ./cmd/aminogolden schema) | node scripts/amino-schema.js
//
// chain-amino.ts renders and parses amino JSON for every sparkdream Msg from it.
const { readFileSync, writeFileSync } = require("fs");
const { join } = require("path");

const schema = JSON.parse(readFileSync(0, "utf8"));
if (!Array.isArray(schema.msgs) || !schema.messages) throw new Error("stdin is not an aminogolden schema");
const out = join(__dirname, "../src-overrides/amino-schema.ts");
writeFileSync(
  out,
  "//@ts-nocheck\n/* eslint-disable */\n" +
    "// GENERATED by scripts/amino-schema.js from the chain's `go run ./cmd/aminogolden schema`.\n" +
    "// Do not edit: rerun the script after every proto sync.\n" +
    `export const aminoSchema = ${JSON.stringify(schema)};\n`,
);
console.log(`wrote ${out}: ${schema.msgs.length} Msgs, ${Object.keys(schema.messages).length} messages`);
